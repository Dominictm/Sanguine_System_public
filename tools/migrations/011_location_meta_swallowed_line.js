'use strict';
// Починка карточек локаций, у которых в строку метаданных втянута следующая строка файла.
//
// Откуда взялось: старый parseLocation().metaField читал значение поля регекспом с `\s*`
// после метки (\s включает перевод строки). У карточки, где ПОСЛЕДНЕЕ поле строки-цитаты
// пустое («… | **Контроль:** »), он захватывал как значение следующую строку — разделитель
// «---», а если его уже не было, то заголовок секции «## 🎭 Атмосфера». Интерфейс показывал
// это в поле, сохранение писало захваченное обратно в строку меты — и строка исчезала из
// карточки. Парсер вылечен (Б21, `[^\S\n]*` в web/lib/parsers/location.js), запись — тоже
// (metaFieldRe в web/routes/locations.js), но уже испорченные файлы чинить некому.
//
// Что делает: значение такого поля заменяет на «—» (принятый в проекте маркер пустоты),
// а проглоченную строку возвращает на место — отдельной строкой сразу за строкой меты.
// Восстанавливается ровно то, что было проглочено: «---» или заголовок, без домысливания
// второй строки (у карточки, пережившей два таких сохранения, «---» уже не вернуть — он
// был удалён ещё первым, и выдумывать его здесь мы не станем).
//
// Идемпотентна: после прогона значение поля — «—», и test() на нём false.

// Только строка-цитата карточки ЛОКАЦИИ (у персонажей поля — бюллеты «- **Поле:**»),
// и только ПОСЛЕДНЕЕ поле строки: проглотить следующую строку могло лишь оно.
const META_LINE = /^>.*\*\*Название:\*\*/;
const SWALLOWED = /(\*\*[^*|\n]+:\*\*)[^\S\n]*(---|##[^|\n]*?)[^\S\n]*$/;

function scan(text) {
  const lines = text.split('\n');
  const idx = lines.findIndex(l => META_LINE.test(l) && SWALLOWED.test(l));
  return idx === -1 ? null : { lines, idx };
}

module.exports = {
  description: 'карточки локаций: вернуть на место строку, втянутую в строку метаданных («**Контроль:** ---»)',

  test(text) {
    return !!scan(text);
  },

  migrate(text) {
    const found = scan(text);
    if (!found) return text;
    const { lines, idx } = found;
    let swallowed = '';
    lines[idx] = lines[idx].replace(SWALLOWED, (_, label, tail) => {
      swallowed = tail.trim();
      return `${label} —`;
    });
    lines.splice(idx + 1, 0, swallowed);
    return lines.join('\n');
  },
};
